"""Sentence-level audit: notebook protocol text vs. the LLM prompts.
Writes PROMPT_AUDIT.md. Run: python audit_prompts.py"""
import re, sys
from pathlib import Path
sys.path.insert(0, str(Path(__file__).resolve().parent))
import cmv_llm_batch as L
P = L.PROTOCOL

def sents(t): return [s.strip() for s in re.split(r'(?<=[.?!])\s+', t) if s.strip()]

def human_texts(m):
    q = P[m]
    t = [P['overview'], P['scale_intro'], *[f"{k}: {v}" for k, v in P['scale'].items()],
         q['full'], q['short'], P['unusual_responses'], L.SCALE_UI_TEXT]
    t += [q['presence_question'], q['comparison_question'], L.EVIDENCE_COMPARE_REMINDER] \
        if m == 'evidence' else [q['question']]
    for i in L.EXAMPLE_INDEX[m]:
        ex = P['examples'][i]; t += [ex['title'], ex['post'], ex['a'], ex['b'], ex['lesson']]
    return t

# Panel titles and field labels as they appear on the annotation screen
UI_LABELS = {"OVERVIEW", "FOUR-WAY COMPARATIVE SCALE", "RESPONSES THAT ARE NOT CLEAR ARGUMENTS",
             "THE ORIGINAL POST", "RESPONSE A", "RESPONSE B", "Worked examples",
             *L.CHOICES, L.EV_A, L.EV_B, L.EVIDENCE_COMPARE_TITLE, "If both are checked:"}

# Hard check: a prompt must never name another metric's task.
OTHER = {"cogency": ["Rhetorical Effectiveness", "rhetorical effectiveness", "Evidential Support"],
         "effectiveness": ["Cogency", "cogency", "cogent", "Evidential Support"],
         "evidence": ["Cogency", "cogency", "cogent", "Rhetorical Effectiveness",
                      "rhetorical effectiveness"]}
for m, names in OTHER.items():
    text = L.system_prompt(m) + "\n" + L.user_prompt(m, "T", "O", "A", "B")
    found = [n for n in names if n in text]
    assert not found, f"{m} prompt mentions another metric: {found}"

out = ["# Prompt audit: notebook protocol vs. LLM prompts", "",
       f"Protocol `{L.PROTOCOL_VERSION}`. Generated by `audit_prompts.py`.", "",
       "Check passed: no prompt names another metric's task.", ""]
for m in L.METRICS:
    full = L.system_prompt(m) + "\n" + L.user_prompt(m, "T", "O", "A", "B")
    hs = [s for t in human_texts(m) for s in sents(t)]
    missing = [s for s in hs if s not in full]
    allh = " ".join(human_texts(m))
    added = []
    for line in full.split("\n"):
        l = line.strip()
        if not l or l == "---" or l in ("T", "O", "A", "B"): continue
        if any(s in l for s in hs if len(s) > 15): continue
        h = l.lstrip("# ")
        if h in allh or h in UI_LABELS or h == P[m]['title']: continue
        added.append(l)
    out += [f"## {L.METRIC_NAME[m]}", "",
            f"**{len(hs) - len(missing)} of {len(hs)} notebook sentences appear verbatim.**", "",
            "Notebook sentences not used verbatim:", ""]
    out += [f"- {s}" for s in missing] or ["- none"]
    out += ["", "Lines in the prompt that are not notebook text or screen labels:", ""]
    out += [f"- {a}" for a in added] or ["- none"]
    out.append("")
Path("PROMPT_AUDIT.md").write_text("\n".join(out), encoding="utf-8")
print("\n".join(out))
